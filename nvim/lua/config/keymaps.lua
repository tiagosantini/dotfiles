local map = vim.keymap.set

vim.g.mapleader = " "
vim.g.maplocalleader = " "

--------------------------------------------------
-- Better window navigation
--------------------------------------------------

map("n", "<C-h>", "<C-w>h")
map("n", "<C-j>", "<C-w>j")
map("n", "<C-k>", "<C-w>k")
map("n", "<C-l>", "<C-w>l")

--------------------------------------------------
-- Clear search highlight
--------------------------------------------------

map("n", "<Esc>", "<cmd>nohlsearch<CR>")

--------------------------------------------------
-- Save
--------------------------------------------------

map("n", "<leader>w", "<cmd>w<CR>")

--------------------------------------------------
-- Quit
--------------------------------------------------

map("n", "<leader>q", "<cmd>q<CR>")
